create sequence if not exists public.salgo_places_id_seq as bigint
  start with 1000 increment by 1;

create table if not exists public.salgo_places (
  id bigint not null default nextval('public.salgo_places_id_seq'),
  name text not null,
  category text not null,
  city text not null,
  address text not null,
  schedule text not null,
  price text not null,
  description text not null,
  rating double precision not null default 0,
  review_count integer not null default 0,
  lat double precision not null,
  lng double precision not null,
  image_url text,
  owner_id uuid,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (id),
  constraint salgo_places_review_count_nonnegative check (review_count >= 0),
  constraint salgo_places_lat_range check (lat between -90 and 90),
  constraint salgo_places_lng_range check (lng between -180 and 180)
);

