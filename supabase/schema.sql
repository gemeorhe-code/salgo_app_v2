create or replace function public.salgo_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.salgo_user_roles r
    where r.user_id = auth.uid() and r.role = 'admin'
  );
$$;

create or replace function public.salgo_is_owner_of(p_place_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    exists (
      select 1
      from public.salgo_user_roles r
      where r.user_id = auth.uid()
        and r.role = 'owner'
        and r.place_id = p_place_id
    )
    or exists (
      select 1
      from public.salgo_places p
      where p.id = p_place_id and p.owner_id = auth.uid()
    );
$$;

create or replace function public.salgo_my_place_access()
returns table (role text, place_ids bigint[])
language sql
stable
security definer
set search_path = ''
as $$
  select 'admin'::text, array[]::bigint[]
  where public.salgo_is_admin()
  union all
  select 'owner'::text, pg_catalog.array_agg(r.place_id order by r.place_id)
  from public.salgo_user_roles r
  where r.user_id = auth.uid()
    and r.role = 'owner'
    and r.place_id is not null
  having pg_catalog.count(r.place_id) > 0;
$$;

create or replace function public.salgo_guard_place_changes()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    new.id := pg_catalog.nextval('public.salgo_places_id_seq');
  end if;

  if new.id is null then
    raise exception 'El lugar debe tener un id válido';
  end if;

  if auth.uid() is null then
    return new;
  end if;

  if not public.salgo_is_admin() then
    if tg_op = 'INSERT' then
      raise exception 'Solo el administrador puede crear lugares';
    end if;

    if not public.salgo_is_owner_of(old.id) then
      raise exception 'No tienes permiso para editar este lugar';
    end if;

    new.owner_id := old.owner_id;
    new.is_active := old.is_active;
  end if;

  new.updated_at := pg_catalog.now();
  return new;
end;
$$;

drop trigger if exists salgo_places_guard on public.salgo_places;
create trigger salgo_places_guard
  before insert or update on public.salgo_places
  for each row execute function public.salgo_guard_place_changes();

create or replace function public.salgo_assign_owner(
  p_email text,
  p_place_id bigint
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid;
begin
  if not public.salgo_is_admin() then
    raise exception 'Solo el administrador puede asignar dueños';
  end if;

  select u.id into v_user_id
  from auth.users u
  where pg_catalog.lower(u.email) =
        pg_catalog.lower(pg_catalog.btrim(p_email))
  limit 1;

  if v_user_id is null then
    return;
  end if;

  update public.salgo_places
  set owner_id = v_user_id
  where id = p_place_id;

  insert into public.salgo_user_roles (user_id, role, place_id)
  select v_user_id, 'owner', p_place_id
  where not exists (
    select 1
    from public.salgo_user_roles r
    where r.user_id = v_user_id
      and r.role = 'owner'
      and r.place_id = p_place_id
  );
end;
$$;

create or replace function public.salgo_remove_owner(
  p_email text,
  p_place_id bigint
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid;
begin
  if not public.salgo_is_admin() then
    raise exception 'Solo el administrador puede quitar dueños';
  end if;

  select u.id into v_user_id
  from auth.users u
  where pg_catalog.lower(u.email) =
        pg_catalog.lower(pg_catalog.btrim(p_email))
  limit 1;

  if v_user_id is null then
    return;
  end if;

  delete from public.salgo_user_roles r
  where r.user_id = v_user_id
    and r.role = 'owner'
    and r.place_id = p_place_id;

  update public.salgo_places
  set owner_id = null
  where id = p_place_id and owner_id = v_user_id;
end;
$$;

